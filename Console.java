package com.mycompany.gamingconsolereport;

/**
 *
 * @author Student
 */
public abstract class Console implements iConsoles {
    private String consoleType;
    private String store;
    private int totalSales;

    // Constructor to set fields
    public Console(String consoleType, String store, int totalSales) {
        this.consoleType = consoleType;
        this.store = store;
        this.totalSales = totalSales;
    }

    // Getter methods implementing iConsoles
    @Override
    public String getConsoleType() {
        return consoleType;
    }

    @Override
    public String getStore() {
        return store;
    }

    @Override
    public int getTotalSales() {
        return totalSales;
    }
}
    

